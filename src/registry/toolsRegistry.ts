export function getCupboardById(id: CupboardId): CupboardDefinition {
  const found = CUPBOARDS.find((c) => c.id === id);
  if (!found) throw new Error(`Unknown cupboard: ${id}`);
  return found;
}

export function getToolsForCupboard(cupboardId: CupboardId): ToolDefinition[] {
  return TOOLS_REGISTRY.filter((t) => t.cupboardId === cupboardId);
}

export function getToolById(toolId: string): ToolDefinition | undefined {
  return TOOLS_REGISTRY.find((t) => t.id === toolId);
}
